package com.example.psychoapp.domain.chat

object CrisisDetector {

    private val CRISIS_PHRASES: List<String> = listOf(
        // ! Прямые суицидальные высказывания
        "не хочу жить",
        "не хочу больше жить",
        "хочу умереть",
        "хочу покончить",
        "покончить с собой",
        "покончу с собой",
        "самоубийств",
        "суицид",
        "убить себя",
        "убью себя",
        "лишить себя жизни",
        "лишу себя жизни",

        // ! Обесценивание собственной жизни
        "не вижу смысла жить",
        "не вижу смысла в жизни",
        "нет смысла жить",
        "смысла жить нет",
        "незачем жить",
        "лучше бы меня не было",
        "лучше бы я умер",
        "хочу исчезнуть навсегда",
        "хочу перестать существовать",
        "устал жить",
        "устала жить",
        "надоело жить",

        // ! Самоповреждение
        "порезать себя",
        "порезал себя",
        "резать себя",
        "режу себя",
        "навредить себе",
        "наврежу себе",
        "причинить себе боль",
        "бью себя",
        "обжигаю себя",

        // ! Конкретные суицидальные сценарии
        "прыгнуть с крыши",
        "прыгнуть с балкона",
        "прыгнуть с моста",
        "наглотаться таблеток",

        // ! Острый кризис
        "не могу больше так жить",
        "хочу сбежать от жизни",
    )

    fun isCrisis(text: String): Boolean {
        val normalized = text.lowercase().trim()
        if (normalized.isEmpty()) return false
        return CRISIS_PHRASES.any { phrase -> normalized.contains(phrase) }
    }
}